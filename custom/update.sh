#!/bin/bash
# Move the custom build onto a newer official StenoAI release.
#
#   custom/update.sh            # latest release
#   custom/update.sh v0.8.1     # a specific tag
#
# 1. Downloads the official DMG for the tag and checks it is signed and
#    notarized by Steno Labs (its native helpers are reused by build.sh).
# 2. Rebases the `custom` branch from the release it was based on onto the new
#    tag. On a conflict it stops so the conflict can be resolved by hand, then
#    rerun this script.
# 3. Refreshes custom/constraints.txt from the new official bundle.
# 4. Builds. Installing stays a separate, explicit step: custom/install.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
TEAM_ID="HSDX294RG4"   # Skrape Limited (Steno Labs)

TAG="${1:-}"
if [ -z "$TAG" ]; then
  TAG=$(curl -fsS https://api.github.com/repos/stenolabs/stenoai/releases/latest \
        | /usr/bin/python3 -c 'import sys,json; print(json.load(sys.stdin)["tag_name"])')
fi
BASE=$(cat custom/BASE)
VERSION="${TAG#v}"
echo "==> Current base $BASE, target $TAG"

# --- 1. official app for the target release ---------------------------------
DEST="$HOME/code/stenoai-official/$TAG"
if [ ! -d "$DEST/StenoAI.app" ]; then
  mkdir -p "$DEST/download"
  DMG="$DEST/download/stenoAI-macos-$VERSION-arm64.dmg"
  curl -fL -sS -o "$DMG" \
    "https://github.com/stenolabs/stenoai/releases/download/$TAG/stenoAI-macos-$VERSION-arm64.dmg"
  MOUNT=$(hdiutil attach -nobrowse -readonly "$DMG" | awk -F'\t' '/\/Volumes\//{print $NF}')
  ditto "$MOUNT/StenoAI.app" "$DEST/StenoAI.app"
  hdiutil detach "$MOUNT" -quiet
  rm -rf "$DEST/download"
fi
codesign --verify --deep --strict "$DEST/StenoAI.app"
codesign -dv "$DEST/StenoAI.app" 2>&1 | grep -q "TeamIdentifier=$TEAM_ID" \
  || { echo "Official app is not signed by Steno Labs ($TEAM_ID)" >&2; exit 1; }
spctl -a "$DEST/StenoAI.app"

# --- 2. rebase our changes ---------------------------------------------------
if [ "$BASE" != "$TAG" ]; then
  git diff --quiet && git diff --cached --quiet \
    || { echo "Uncommitted changes in $ROOT; commit or stash them first" >&2; exit 1; }
  git fetch -q --tags origin
  git rebase --onto "$TAG" "$BASE" custom || {
    echo "Rebase stopped on a conflict. Resolve it, 'git rebase --continue', then"
    echo "set custom/BASE to $TAG, commit, and run custom/build.sh $DEST/StenoAI.app"
    exit 1
  }
  echo "$TAG" > custom/BASE
fi

# --- 3. pin backend packages to the new official versions --------------------
INTERNAL="$DEST/StenoAI.app/Contents/Resources/stenoai/_internal"
{
  echo "# Versions bundled in the official StenoAI $VERSION backend (read from its"
  echo "# _internal/*.dist-info). Regenerated by custom/update.sh."
  for d in "$INTERNAL"/*.dist-info; do
    name=$(basename "$d" .dist-info)
    pkg="${name%-*}"; ver="${name##*-}"
    case "$pkg" in setuptools|httpx2|httpcore2|tqdm) continue ;; esac
    echo "${pkg//_/-}==$ver"
  done
} > custom/constraints.txt
if ! git diff --quiet -- custom/BASE custom/constraints.txt; then
  git add custom/BASE custom/constraints.txt
  git commit -q -m "custom: base on official $TAG"
fi

# --- 4. build ----------------------------------------------------------------
custom/build.sh "$DEST/StenoAI.app"
echo "==> Built on $TAG. Install with: custom/install.sh"
